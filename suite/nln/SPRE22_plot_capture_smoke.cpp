#include "spre22_plot_capture.hpp"

int main(int argc, const char* argv[]) {
    if (argc != 2) return 2;
    using namespace Ariadne;
    const RealVariable x("x"), y("y");
    const EnclosureConfiguration configuration(
        TaylorFunctionFactory(ThresholdSweeper<FloatDP>(dp, 1e-8)));
    HybridEnclosure enclosure(
        HybridExactBox(DiscreteLocation(1), RealSpace({x, y}),
                       ExactBoxType({{-1, 1}, {-2, 2}})),
        configuration);
    const auto coordinates = EffectiveVectorMultivariateFunction::identity(2u);
    const DiscreteEvent invariant("invariant");
    const DiscreteEvent activation("activation");
    const DiscreteEvent bounded("bounded");
    enclosure.new_invariant(invariant, coordinates[0]);
    enclosure.new_activation(activation, coordinates[1]);
    enclosure.new_state_constraint(bounded, ValidatedConstraint(-1, coordinates[0], 1));
    // First capture has no state time variable (ordinary 3-output mapping).
    // Second capture includes t in the state. It must not be duplicated.
    const RealVariable t("t");
    HybridEnclosure time_enclosure(
        HybridExactBox(DiscreteLocation(1), RealSpace({t, x, y}),
                       ExactBoxType({{0, 1}, {-1, 1}, {-2, 2}})),
        configuration);
    ListSet<HybridEnclosure> reach(enclosure);
    reach.adjoin(time_enclosure);
    SPRE22Capture::write_binary(argv[1], reach, Variables2d(x, y));
    std::ifstream in(argv[1], std::ios::binary);
    if (!in) return 3;
    const auto header = SPRE22Capture::read_header(in);
    if (header.first != 0u || header.count != 2u) return 4;
    const auto item = SPRE22Capture::read_record(in, 0u);
    if (item.original_index != 0u || item.projection.n != 3u ||
        item.set.domain().size() != 2u || item.set.constraints().size() != 3u)
        return 5;
    if (item.legacy_extra_time || item.set.function().result_size() != 3u) return 6;
    const auto time_item = SPRE22Capture::read_record(in, 1u);
    if (time_item.legacy_extra_time || time_item.projection.n != 3u ||
        time_item.set.function().result_size() != 3u) return 7;
    if (in.peek() != std::char_traits<char>::eof()) return 8;

    // Exercise the on-disk format generated by the original writer:
    // it used the unlabelled Enclosure method and emitted an extra t.
    // This fixture must remain readable without re-running evolution.
    const std::string old_path = std::string(argv[1]) + ".legacy";
    {
        std::ofstream legacy(old_path, std::ios::binary | std::ios::trunc);
        if (!legacy) return 9;
        SPRE22Capture::write_header(legacy, {0u, 1u});
        const auto old_function =
            time_enclosure.continuous_set().state_time_auxiliary_function();
        SPRE22Capture::write_record_with_mapping(
            legacy, time_enclosure, Variables2d(x, y), 0u, old_function);
    }
    std::ifstream legacy(old_path, std::ios::binary);
    if (!legacy) return 10;
    const auto old_header = SPRE22Capture::read_header(legacy);
    if (old_header.count != 1u || old_header.first != 0u) return 11;
    const auto old_item = SPRE22Capture::read_record(legacy, 0u);
    if (!old_item.legacy_extra_time || old_item.projection.n != 3u ||
        old_item.set.function().result_size() != 4u) return 12;
    if (legacy.peek() != std::char_traits<char>::eof()) return 13;

    // Validate length-prefixed skipping: select the second enclosure
    // without reconstructing the first, as used by replay-range debugging.
    std::ifstream selected(argv[1], std::ios::binary);
    if (!selected) return 14;
    const auto selected_header = SPRE22Capture::read_header(selected);
    if (selected_header.first != 0u || selected_header.count != 2u) return 15;
    SPRE22Capture::skip_record(selected, 0u);
    const auto selected_item = SPRE22Capture::read_record(selected, 1u);
    if (selected_item.original_index != 1u || selected_item.legacy_extra_time) return 16;
    if (selected.peek() != std::char_traits<char>::eof()) return 17;
    return 0;
}
